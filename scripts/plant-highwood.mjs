// Bakes Highwood's planting into src/assets/geometry/highwood-plants.ts. It runs
// after the terrain bake as part of `npm run island:generate`, because the
// habitats read the baked ground.
import { Buffer } from 'node:buffer'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { URL } from 'node:url'
import { plantingEncoding as encoding } from '../src/assets/geometry/island-preview.ts'
import { plantingSources } from '../src/worlds/starter/generation/bake-sources.ts'
import { groundCoverAt, plantHighwood } from '../src/worlds/starter/generation/plant-highwood.ts'
import { plantingLayers } from '../src/worlds/starter/highwood-planting.ts'
import { plantingAges, plantingExposures } from '../src/worlds/starter/layout/highwood-planting.ts'
import { highwoodGeneration } from '../src/worlds/starter/layout/island-generation.ts'

const fullTurn = Math.PI + Math.PI
const speciesByte = 4, packedByte = 5, headingByte = 6, scaleByte = 7
const zOffset = 2
const byteMax = 255
const indent = 2
const millisecondsPerSecond = 1000
const bytesPerKilobyte = 1024

function sourceHash() {
  const hash = createHash('sha256')
  for (const path of plantingSources) hash.update(path).update(readFileSync(new URL(`../${path}`, import.meta.url)))
  return hash.digest('hex')
}

const started = Date.now()
const plants = plantHighwood()
const { west, south } = highwoodGeneration.grid
const species = [...new Set(plants.map((plant) => plant.species))].sort()
const bytes = Buffer.alloc(plants.length * encoding.bytesPerPlant)
const { layerBits, ageBits, exposureBits } = encoding
plants.forEach((plant, index) => {
  const at = index * encoding.bytesPerPlant
  bytes.writeUInt16LE(Math.round((plant.x - west) / encoding.positionStepM), at)
  bytes.writeUInt16LE(Math.round((plant.z - south) / encoding.positionStepM), at + zOffset)
  bytes[at + speciesByte] = species.indexOf(plant.species)
  bytes[at + packedByte] = plantingLayers.indexOf(plant.layer) | (plantingAges.indexOf(plant.age) << layerBits)
    | (plantingExposures.indexOf(plant.exposure) << (layerBits + ageBits)) | (plant.variant << (layerBits + ageBits + exposureBits))
  const turn = ((plant.heading / fullTurn) % 1 + 1) % 1
  bytes[at + headingByte] = Math.round(turn * encoding.turnSteps) % encoding.turnSteps
  bytes[at + scaleByte] = Math.max(0, Math.min(byteMax, Math.round((plant.scale - 1) / encoding.scaleStep + encoding.scaleCentre)))
})

// The ground raster, sampled at cell corners so the game can blend between them.
const { cell, columns, rows } = highwoodGeneration.grid
const groundColumns = Math.floor(columns * cell / encoding.groundCellM) + 1
const groundRows = Math.floor(rows * cell / encoding.groundCellM) + 1
const ground = Buffer.alloc(groundColumns * groundRows * encoding.groundChannels)
for (let j = 0; j < groundRows; j++) {
  for (let i = 0; i < groundColumns; i++) {
    const cover = groundCoverAt({ x: west + i * encoding.groundCellM, z: south + j * encoding.groundCellM })
    const at = (j * groundColumns + i) * encoding.groundChannels
    const values = [cover.litter, cover.heath, cover.moss, cover.bracken]
    values.forEach((value, channel) => {
      ground[at + channel] = Math.round(value * byteMax)
    })
  }
}

const assetPath = new URL('../src/assets/geometry/highwood-plants.ts', import.meta.url)
writeFileSync(assetPath, `// Generated by scripts/plant-highwood.mjs from the Highwood habitats and stand tables.
// Do not edit by hand: change the tables and run npm run island:generate.
export const highwoodPlants = {
  sourceHash: '${sourceHash()}',
  west: ${west},
  south: ${south},
  species: ${JSON.stringify(species).replaceAll('"', '\'').replaceAll(',', ', ')},
  plants: '${bytes.toString('base64')}',
  groundColumns: ${groundColumns},
  groundRows: ${groundRows},
  ground: '${ground.toString('base64')}',
} as const
`)
const counts = Object.fromEntries(plantingLayers.map((layer) => [layer, plants.filter((plant) => plant.layer === layer).length]))
process.stdout.write(JSON.stringify({ seconds: (Date.now() - started) / millisecondsPerSecond, plants: plants.length, ...counts, kilobytes: Math.round((bytes.length + ground.length) / bytesPerKilobyte) }, null, indent) + `\nAsset: ${assetPath.pathname}\n`)
