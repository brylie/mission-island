// Bakes the source tree's graded roads into src/assets/geometry/road-layer.ts: the grading
// raster's tiles, the culverts and the formation distance the terrain is cut to, so the game
// reads them instead of grading the roads on load. It runs after the terrain bake and before the
// planting as part of `npm run island:generate`; `npm run island:roads` runs it, then the planting.
import { Buffer } from 'node:buffer'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { URL } from 'node:url'
import { roadLayerEncoding as encoding } from '../src/assets/geometry/island-preview.ts'
import { roadNetwork } from '../src/assets/geometry/road-kinds.ts'
import { gradeRoadLayer } from '../src/roads.ts'
import { roadSources } from '../src/worlds/starter/generation/bake-sources.ts'

const floatBytes = 4, shortBytes = 2
const indent = 2
const millisecondsPerSecond = 1000
const bytesPerKilobyte = 1024
const { tileKeyStride } = roadNetwork

function sourceHash() {
  const hash = createHash('sha256')
  for (const path of roadSources) hash.update(path).update(readFileSync(new URL(`../${path}`, import.meta.url)))
  return hash.digest('hex')
}

// Tile keys as i16 column and row pairs, in the order given.
function tileList(keys) {
  const out = Buffer.alloc(keys.length * shortBytes * shortBytes)
  keys.forEach((key, k) => {
    const tx = Math.round(key / tileKeyStride)
    out.writeInt16LE(tx, k * shortBytes * shortBytes)
    out.writeInt16LE(key - tx * tileKeyStride, k * shortBytes * shortBytes + shortBytes)
  })
  return out
}

const started = Date.now()
const layer = gradeRoadLayer()
const rasterKeys = [...layer.tiles.keys()].sort((a, b) => a - b)
const raster = Buffer.concat(rasterKeys.map((key) => {
  const delta = layer.tiles.get(key)
  const out = Buffer.alloc(delta.length * floatBytes)
  delta.forEach((value, i) => {
    out.writeFloatLE(value, i * floatBytes)
  })
  return out
}))
const formationKeys = [...layer.formationTiles.keys()].sort((a, b) => a - b)
const formation = Buffer.concat(formationKeys.map((key) => {
  const values = layer.formationTiles.get(key)
  const out = Buffer.alloc(values.length * shortBytes)
  values.forEach((value, i) => {
    const step = Math.max(-encoding.formationFar + 1, Math.min(encoding.formationFar - 1, Math.round(value / encoding.formationStepM)))
    out.writeInt16LE(Number.isFinite(value) ? step : encoding.formationFar, i * shortBytes)
  })
  return out
}))
const point = (p) => (p ? `{ x: ${p.x}, z: ${p.z} }` : 'null')
const culverts = layer.culverts.map((c) => `    { road: '${c.road}', along: ${c.along}, inlet: ${point(c.inlet)}, outlet: ${point(c.outlet)}, depth: ${c.depth} },`).join('\n')

const assetPath = new URL('../src/assets/geometry/road-layer.ts', import.meta.url)
const source = `// Generated by scripts/bake-roads.mjs from the graded roads in src/worlds/starter/layout/roads.ts.
// Do not edit by hand: change the roads and run npm run island:roads.
export const roadLayer = {
  sourceHash: '${sourceHash()}',
  layoutKey: '${layer.key}',
  rasterTiles: '${tileList(rasterKeys).toString('base64')}',
  raster: '${raster.toString('base64')}',
  formationTiles: '${tileList(formationKeys).toString('base64')}',
  formation: '${formation.toString('base64')}',
  culverts: [${culverts ? `\n${culverts}\n  ` : ''}],
} as const
`
writeFileSync(assetPath, source)
process.stdout.write(JSON.stringify({
  seconds: (Date.now() - started) / millisecondsPerSecond,
  rasterTiles: rasterKeys.length,
  formationTiles: formationKeys.length,
  culverts: layer.culverts.length,
  kilobytes: Math.round(Buffer.byteLength(source) / bytesPerKilobyte),
}, null, indent) + `\nAsset: ${assetPath.pathname}\n`)
