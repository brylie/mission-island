// Generates the crew dye swatches from the dye recipe. Run
// `npm run dyes:generate` to rewrite src/assets/recipes/dye-swatches.ts;
// never edit a swatch by hand. See docs/design/color-direction.md#player-dyes.
import {
  chromaSearch, degreesPerHalfTurn, gamutTolerance, hexChannel, lmsRootExponent, lmsToLinearSrgb, oklabToLmsRoot, srgbTransfer,
} from './assets/recipes/color-space.ts'
import { dyeGamutMargin, dyeHueNames, dyeHues, dyeNeutrals, dyeRowNames, dyeRows } from './assets/recipes/dye-palette.ts'

export { dyeHues, dyeRows }

interface DyeSwatch {
  name: string
  row: 'pale' | 'mid' | 'deep' | 'neutral'
  hue?: number
  color: string
  // The rolled cuffs, buttons and cap brim.
  trim: string
}

type Row = readonly [number, number, number]
const dot = (row: Row, v: readonly number[]) => row.reduce((sum, weight, i) => sum + weight * v[i], 0)

function toSrgb(c: number) {
  const { linearLimit, linearSlope, scale, offset, gamma } = srgbTransfer
  return c <= linearLimit ? linearSlope * c : scale * c ** (1 / gamma) - offset
}

function oklchToLinear(lightness: number, chroma: number, hue: number) {
  const angle = (hue * Math.PI) / degreesPerHalfTurn
  const lab = [lightness, chroma * Math.cos(angle), chroma * Math.sin(angle)]
  const lms = oklabToLmsRoot.map((row) => dot(row, lab) ** lmsRootExponent)
  return lmsToLinearSrgb.map((row) => dot(row, lms))
}

const inGamut = (rgb: number[]) => rgb.every((c) => c >= -gamutTolerance && c <= 1 + gamutTolerance)

function maxChroma(lightness: number, hue: number) {
  let lo = 0, hi: number = chromaSearch.ceiling
  for (let i = 0; i < chromaSearch.steps; i++) {
    const mid = lo + (hi - lo) * chromaSearch.split
    if (inGamut(oklchToLinear(lightness, mid, hue))) lo = mid
    else hi = mid
  }
  return lo
}

function oklchHex(lightness: number, chroma: number, hue: number) {
  const channel = (c: number) => Math.round(Math.max(0, Math.min(1, toSrgb(c))) * hexChannel.max)
    .toString(hexChannel.radix).padStart(hexChannel.digits, '0')
  return '#' + oklchToLinear(lightness, chroma, hue).map(channel).join('')
}

// Pale and mid swatches take the deep step of their hue as trim, and deep
// swatches take the pale step, so a cuff always breaks from the forearm.
export function generateDyeSwatches(): Record<string, DyeSwatch> {
  const colors = new Map<string, string>()
  for (const { row, lightness, chroma } of dyeRows) {
    for (const hue of dyeHues) {
      colors.set(`${row}-${hue}`, oklchHex(lightness, Math.min(chroma, maxChroma(lightness, hue) * dyeGamutMargin), hue))
    }
  }
  const swatches: Record<string, DyeSwatch> = {}
  for (const { row } of dyeRows) {
    for (const hue of dyeHues) {
      swatches[`${row}-${hue}`] = {
        name: `${dyeRowNames[row]} ${dyeHueNames[hue].toLowerCase()}`, row, hue,
        color: colors.get(`${row}-${hue}`)!, trim: colors.get(`${row === 'deep' ? 'pale' : 'deep'}-${hue}`)!,
      }
    }
  }
  for (const [id, neutral] of Object.entries(dyeNeutrals)) swatches[id] = { ...neutral, row: 'neutral' }
  return swatches
}

export function dyeSwatchesSource(swatches = generateDyeSwatches()) {
  const lines = Object.entries(swatches).map(([id, s]) =>
    `  '${id}': { name: '${s.name}', row: '${s.row}', ${s.hue === undefined ? '' : `hue: ${s.hue}, `}color: '${s.color}', trim: '${s.trim}' },`)
  return `// Generated by \`npm run dyes:generate\` from src/assets/recipes/dye-palette.ts. Do not edit by hand.\n` +
    `export const dyeSwatches = {\n${lines.join('\n')}\n} as const\n\nexport type DyeSwatchId = keyof typeof dyeSwatches\n`
}
